const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '../..');
const content = fs.readFileSync(
  path.join(rootDir, 'webapp/src/engine/data/SkillDataGen.ts'),
  'utf-8'
);

function extractArray(content, varName) {
  const startIdx = content.indexOf(`export const ${varName} = [`);
  if (startIdx === -1) return [];
  const firstBracket = content.indexOf('[', startIdx);

  let bracketCount = 0;
  let endIdx = -1;
  for (let i = firstBracket; i < content.length; i++) {
    if (content[i] === '[') bracketCount++;
    if (content[i] === ']') bracketCount--;
    if (bracketCount === 0) {
      endIdx = i;
      break;
    }
  }

  const arrStr = content.substring(firstBracket, endIdx + 1);
  return eval(arrStr);
}

try {
  const normalData = extractArray(content, 'normalSkillData');
  const uniqueData = extractArray(content, 'uniqueSkillData');
  
  const skillRarityMap = {};
  
  // Combine all and iterate
  [...normalData, ...uniqueData].forEach(skillDef => {
    if (skillDef.variants) {
      skillDef.variants.forEach(variant => {
        let rarityCategory = "white"; // normal, including passive, bad skills, double
        
        if (variant.rarity === "unique") {
          rarityCategory = "green"; // Inherited Unique skills
        } else if (variant.rarity === "rare") {
          rarityCategory = "gold"; // Gold skills
        } else if (variant.id && variant.id >= 10000 && variant.id < 200000) {
          rarityCategory = "green"; // Early renamed inherited unique skills & original unique skills
        }
        
        // Ensure parent type checking
        if (skillDef.type === "unique") {
          rarityCategory = "green";
        }
        
        skillRarityMap[variant.name] = rarityCategory;
      });
    } else {
       // If variant is missing, use skillDef itself
       let rarityCategory = "white";
       if (skillDef.type === "unique" || skillDef.rarity === "unique") {
          rarityCategory = "green";
       } else if (skillDef.rarity === "rare") {
          rarityCategory = "gold";
       } else if (skillDef.id && skillDef.id >= 10000 && skillDef.id < 200000) {
          rarityCategory = "green";
       }
       
       if (skillDef.name) {
          skillRarityMap[skillDef.name] = rarityCategory;
       }
    }
  });

  const tsContent = `// Auto-generated by extract_skill_info.js
export type SkillRarity = 'white' | 'gold' | 'green';
export const skillRarityMap: Record<string, SkillRarity> = ${JSON.stringify(skillRarityMap, null, 2)};

export function getSkillRarityInfo(skillName: string) {
  const rarity = skillRarityMap[skillName] || 'white';
  switch (rarity) {
    case 'gold':
      return { icon: '✦ ', colorClass: 'text-amber-400' };
    case 'green':
      return { icon: '❖ ', colorClass: 'text-emerald-400' };
    default:
      return { icon: '', colorClass: 'text-zinc-200' };
  }
}
`;

  fs.writeFileSync(path.join(rootDir, 'desktop-app/app/lib/skillRarityData.ts'), tsContent);
  console.log('Successfully generated skillRarityData.ts with ' + Object.keys(skillRarityMap).length + ' skills.');

} catch(e) {
  console.error("Failed to parse array:", e);
}
