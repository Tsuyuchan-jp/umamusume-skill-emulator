/**
 * master.mdb から直接 skillRarityData.ts を生成する。
 * 旧 extract_skill_info.js（SkillDataGen.ts 経由）の置き換え。
 */
const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');

const rootDir = path.join(__dirname, '../..');
const mdbPath = path.join(rootDir, 'master.mdb');
const outPath = path.join(rootDir, 'desktop-app/app/lib/skillRarityData.ts');

function getUmaRarity(rarity, id) {
  if (rarity === 6) return 'evo';
  if (rarity === 5) return 'unique';
  if (rarity === 4 || rarity === 3) {
    if (rarity === 4 || id > 100000) return 'rare';
    return 'normal';
  }
  if (rarity === 2 || rarity === 1) {
    if (rarity === 2) return 'rare';
    if (id % 10 === 1) return 'double';
    return 'normal';
  }
  return 'normal';
}

/** extract_skill_info.js と同等の UI 色分け */
function toUiRarityCategory(rarityStr, id) {
  let category = 'white';

  if (rarityStr === 'unique') {
    category = 'green';
  } else if (rarityStr === 'rare') {
    category = 'gold';
  } else if (id >= 10000 && id < 200000) {
    category = 'green';
  }

  return category;
}

if (!fs.existsSync(mdbPath)) {
  console.error('master.mdb が見つかりません。リポジトリルートに配置してください:');
  console.error(mdbPath);
  process.exit(1);
}

const db = new Database(mdbPath, { readonly: true });

const textRows = db.prepare('SELECT `index`, text FROM text_data WHERE category=47').all();
const nameMap = {};
for (const row of textRows) {
  nameMap[row.index] = row.text;
}

const skillRows = db.prepare('SELECT id, rarity FROM skill_data').all();
const skillRarityMap = {};

for (const row of skillRows) {
  const id = row.id;
  const name = nameMap[id];
  if (!name) continue;

  const rarityStr = getUmaRarity(row.rarity, id);
  skillRarityMap[name] = toUiRarityCategory(rarityStr, id);
}

const tsContent = `// Auto-generated by tools/mdb-extractor/extract_rarity_from_mdb.js
export type SkillRarity = 'white' | 'gold' | 'green';
export const skillRarityMap: Record<string, SkillRarity> = ${JSON.stringify(skillRarityMap, null, 2)};

export function getSkillRarityInfo(skillName: string) {
  const rarity = skillRarityMap[skillName] || 'white';
  switch (rarity) {
    case 'gold':
      return { icon: '✦ ', colorClass: 'text-amber-400' };
    case 'green':
      return { icon: '❖ ', colorClass: 'text-emerald-400' };
    default:
      return { icon: '', colorClass: 'text-zinc-200' };
  }
}
`;

fs.writeFileSync(outPath, tsContent, 'utf8');
console.log(
  'Successfully generated skillRarityData.ts with ' +
    Object.keys(skillRarityMap).length +
    ' skills.'
);
console.log('Output: ' + outPath);

db.close();
